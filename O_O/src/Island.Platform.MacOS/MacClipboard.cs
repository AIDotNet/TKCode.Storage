using System.Runtime.InteropServices;

namespace Island.Platform.MacOS;

/// <summary>
/// macOS clipboard support: <c>NSPasteboard.changeCount</c>, the nspasteboard.org concealed / transient markers, and
/// direct paste by re-activating the last foreground app and posting Cmd+V through Quartz events (needs the
/// Accessibility permission; without it macOS drops the event, so it is checked first).
/// </summary>
public sealed partial class MacClipboard : IClipboardPlatform
{
    private const string AppServices = "/System/Library/Frameworks/ApplicationServices.framework/ApplicationServices";
    private const string CoreFoundation = "/System/Library/Frameworks/CoreFoundation.framework/CoreFoundation";
    private const ushort KeyV = 9;                      // kVK_ANSI_V
    private const ulong CommandFlag = 0x100000;         // kCGEventFlagMaskCommand
    private const uint ActivateIgnoringOtherApps = 2;   // NSApplicationActivateIgnoringOtherApps

    private static readonly string[] SecretTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

    private readonly int _ownPid = Environment.ProcessId;
    private nint _target; // NSRunningApplication, retained

    public long? ChangeCount => (long)ObjC.Send(Pasteboard(), ObjC.Sel("changeCount"));

    public bool IsConcealed()
    {
        var types = ObjC.Send(Pasteboard(), ObjC.Sel("types"));
        if (types == 0)
        {
            return false;
        }
        foreach (var type in SecretTypes)
        {
            if (ObjC.SendByte(types, ObjC.Sel("containsObject:"), NSString(type)) != 0)
            {
                return true;
            }
        }
        return false;
    }

    public void TrackForegroundApp()
    {
        var workspace = ObjC.Send(ObjC.Class("NSWorkspace"), ObjC.Sel("sharedWorkspace"));
        var app = ObjC.Send(workspace, ObjC.Sel("frontmostApplication"));
        if (app == 0 || (int)ObjC.Send(app, ObjC.Sel("processIdentifier")) == _ownPid || app == _target)
        {
            return;
        }
        ObjC.Send(app, ObjC.Sel("retain"));
        if (_target != 0)
        {
            ObjC.Send(_target, ObjC.Sel("release"));
        }
        _target = app;
    }

    public string? TargetAppName => _target == 0 ? null : FromNSString(ObjC.Send(_target, ObjC.Sel("localizedName")));

    public void RestoreFocus()
    {
        if (_target != 0)
        {
            ObjC.SendByte(_target, ObjC.Sel("activateWithOptions:"), (nint)ActivateIgnoringOtherApps);
        }
    }

    public PasteResult Paste()
    {
        if (!AXIsProcessTrusted())
        {
            PromptForAccessibility();
            return new(false, "直接粘贴需要\"辅助功能\"权限：请在 系统设置 › 隐私与安全性 › 辅助功能 中允许 O_O。已复制到剪贴板。");
        }
        if (_target != 0)
        {
            ObjC.SendByte(_target, ObjC.Sel("activateWithOptions:"), (nint)ActivateIgnoringOtherApps);
            Thread.Sleep(80); // let the app come forward before the keystroke reaches it
        }
        foreach (var down in new[] { true, false })
        {
            var e = CGEventCreateKeyboardEvent(0, KeyV, down);
            if (e == 0)
            {
                return new(false, "无法创建按键事件。已复制到剪贴板。");
            }
            CGEventSetFlags(e, CommandFlag);
            CGEventPost(0, e); // kCGHIDEventTap
            CFRelease(e);
        }
        return PasteResult.Done;
    }

    /// <summary>Opens the system prompt that leads the user to the Accessibility settings (once per launch at most).</summary>
    private static bool _prompted;

    private static void PromptForAccessibility()
    {
        if (_prompted)
        {
            return;
        }
        _prompted = true;
        var yes = ObjC.Send(ObjC.Class("NSNumber"), ObjC.Sel("numberWithBool:"), 1);
        var options = SendTwo(ObjC.Class("NSDictionary"), ObjC.Sel("dictionaryWithObject:forKey:"), yes, NSString("AXTrustedCheckOptionPrompt"));
        AXIsProcessTrustedWithOptions(options);
    }

    private static nint Pasteboard() => ObjC.Send(ObjC.Class("NSPasteboard"), ObjC.Sel("generalPasteboard"));

    private static nint NSString(string s)
    {
        var utf8 = Marshal.StringToCoTaskMemUTF8(s);
        try
        {
            return ObjC.Send(ObjC.Class("NSString"), ObjC.Sel("stringWithUTF8String:"), utf8);
        }
        finally
        {
            Marshal.FreeCoTaskMem(utf8);
        }
    }

    private static string? FromNSString(nint s) =>
        s == 0 ? null : Marshal.PtrToStringUTF8(ObjC.Send(s, ObjC.Sel("UTF8String")));

    // A two-argument objc_msgSend, kept here so the shared ObjC helpers stay untouched.
    [LibraryImport("/usr/lib/libobjc.A.dylib", EntryPoint = "objc_msgSend")]
    private static partial nint SendTwo(nint receiver, nint selector, nint a, nint b);

    [LibraryImport(AppServices)]
    [return: MarshalAs(UnmanagedType.U1)]
    private static partial bool AXIsProcessTrusted();

    [LibraryImport(AppServices)]
    [return: MarshalAs(UnmanagedType.U1)]
    private static partial bool AXIsProcessTrustedWithOptions(nint options);

    [LibraryImport(AppServices)]
    private static partial nint CGEventCreateKeyboardEvent(nint source, ushort key, [MarshalAs(UnmanagedType.U1)] bool down);

    [LibraryImport(AppServices)]
    private static partial void CGEventSetFlags(nint e, ulong flags);

    [LibraryImport(AppServices)]
    private static partial void CGEventPost(uint tap, nint e);

    [LibraryImport(CoreFoundation)]
    private static partial void CFRelease(nint obj);
}
